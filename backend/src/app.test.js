jest.mock('./config/database', () => ({ query: jest.fn(), getConnection: jest.fn() }))
jest.mock('./shared/lib/logger', () => ({ info: jest.fn(), error: jest.fn() }))
jest.mock('@scalar/express-api-reference', () => ({ apiReference: () => (req, res) => res.send('docs') }))
const request = require('supertest')
const jwt = require('jsonwebtoken')
const pool = require('./config/database')
const app = require('./app')
const auth = (papel = 'admin') => 'Bearer ' + jwt.sign({ id: 7, papel }, process.env.JWT_SECRET)
beforeEach(() => jest.resetAllMocks())

test.each(['http://localhost:5173', 'http://localhost:4173', 'http://127.0.0.1:5173'])('CORS libera preflight de PUT com Bearer para %s', async (origin) => {
  const r = await request(app).options('/cargo/1').set('Origin', origin)
    .set('Access-Control-Request-Method', 'PUT')
    .set('Access-Control-Request-Headers', 'authorization,content-type')
  expect(r.status).toBe(200)
  expect(r.headers['access-control-allow-origin']).toBe(origin)
  expect(r.headers['access-control-allow-methods']).toContain('PUT')
})
test('origem externa não recebe permissão CORS', async () => {
  const r = await request(app).options('/marca').set('Origin', 'https://nao-permitido.example')
    .set('Access-Control-Request-Method', 'POST')
  expect(r.headers['access-control-allow-origin']).toBeUndefined()
})
test('protege rotas e impede escrita administrativa de vendedor', async () => {
  expect((await request(app).get('/estoque')).status).toBe(401)
  expect((await request(app).post('/cargo').set('Authorization', auth('funcionario')).send({ nome: 'Cargo', nivelAcesso: 10 })).status).toBe(403)
  expect(pool.query).not.toHaveBeenCalled()
})
test('cargo recebe e retorna contrato camelCase', async () => {
  pool.query.mockResolvedValueOnce([{ insertId: 3 }])
    .mockResolvedValueOnce([[{ idCargo: 3, nome: 'Vendedor', nivelAcesso: 10 }]])
  const r = await request(app).post('/cargo').set('Authorization', auth()).send({ nome: 'Vendedor', nivelAcesso: 10 })
  expect(r.status).toBe(201)
  expect(r.body.dados).toEqual({ idCargo: 3, nome: 'Vendedor', nivelAcesso: 10 })
})
test('modelo exige categoria e injeta responsável do token', async () => {
  const missing = await request(app).post('/modelo').set('Authorization', auth()).send({ nome: 'Runner', idMarca: 1 })
  expect(missing.status).toBe(400)
  pool.query.mockResolvedValueOnce([{ insertId: 1 }]).mockResolvedValueOnce([[{ idModelo: 1 }]])
  const r = await request(app).post('/modelo').set('Authorization', auth()).send({ nome: 'Runner', idMarca: 1, idCategoria: 2, idFuncionarioCadastro: 999 })
  expect(r.status).toBe(201)
  expect(pool.query.mock.calls[0][1]).toEqual(['Runner', 1, 2, 7])
})
test('paginação e JSON malformado retornam 400', async () => {
  expect((await request(app).get('/venda?limite=1.5').set('Authorization', auth())).status).toBe(400)
  expect((await request(app).get('/venda?cursor=lixo').set('Authorization', auth())).status).toBe(400)
  expect((await request(app).post('/marca').set('Authorization', auth()).set('Content-Type', 'application/json').send('{')).status).toBe(400)
})
